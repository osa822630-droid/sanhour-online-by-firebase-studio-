import 'dart:io';
import 'package:flutter/material.dart';
import 'package:flutter_rating_bar/flutter_rating_bar.dart';
import 'package:image_picker/image_picker.dart';
import 'package:intl/intl.dart';
import 'package:provider/provider.dart';
import 'package:sanhour_online/models/review_model.dart';
import 'package:sanhour_online/providers/auth_provider.dart' as app_auth;
import 'package:sanhour_online/services/api_service.dart';
import 'package:sanhour_online/services/media_upload_service.dart';
import 'package:sanhour_online/widgets/cached_image.dart';

class ReviewScreen extends StatefulWidget {
  final String itemId;
  final String itemType;
  final String itemName;

  const ReviewScreen({
    super.key,
    required this.itemId,
    required this.itemType,
    required this.itemName,
  });

  @override
  State<ReviewScreen> createState() => _ReviewScreenState();
}

class _ReviewScreenState extends State<ReviewScreen> {
  double _rating = 0;
  final TextEditingController _reviewController = TextEditingController();
  final List<String> _selectedImages = [];
  final ImagePicker _imagePicker = ImagePicker();

  bool _isSubmitting = false;
  bool _isImageUploading = false;

  // ✅ Fix #71: تخزين الـ future في الـ state لمنع إعادة الجلب عند كل setState
  late Future<List<Review>> _reviewsFuture;

  @override
  void initState() {
    super.initState();
    _reviewsFuture = ApiService.getReviews(widget.itemId);
  }

  void _refreshReviews() {
    setState(() {
      _reviewsFuture = ApiService.getReviews(widget.itemId);
    });
  }

  @override
  void dispose() {
    _reviewController.dispose();
    super.dispose();
  }

  Future<void> _pickImage() async {
    try {
      final XFile? image = await _imagePicker.pickImage(
        source: ImageSource.gallery,
        maxWidth: 1000,
        maxHeight: 1000,
        imageQuality: 80,
      );

      if (image != null) {
        if (!mounted) return;
        setState(() => _isImageUploading = true);

        // ✅ إصلاح الكراش: MediaUploadService بدل putFile الخام
        // — تحقق من الحجم، رسائل خطأ عربية، إعادة محاولة تلقائية
        final uploadedImageUrl = await MediaUploadService.uploadFile(
          file: File(image.path),
          folder: 'reviews_images',
          kind: MediaKind.image,
        );

        if (!mounted) return;
        setState(() {
          _selectedImages.add(uploadedImageUrl);
          _isImageUploading = false;
        });
      }
    } on MediaUploadException catch (e) {
      if (!mounted) return;
      setState(() => _isImageUploading = false);
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text(e.userMessage), backgroundColor: Colors.red));
    } catch (e) {
      if (!mounted) return;
      setState(() => _isImageUploading = false);
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('فشل رفع الصورة: ${e.toString().replaceAll("Exception:", "")}'),
          backgroundColor: Colors.red,
        ),
      );
    }
  }

  void _removeImage(String image) {
    setState(() {
      _selectedImages.remove(image);
    });
  }

  Future<void> _submitReview() async {
    // ✅ QA Fix #07: استخدام AuthProvider دائماً — يدعم كلاً من Firebase Auth والـ Mock
    final authProvider = Provider.of<app_auth.AuthProvider>(context, listen: false);

    if (!authProvider.isLoggedIn || authProvider.isGuest) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('يجب تسجيل الدخول لإضافة تقييم')),
      );
      return;
    }

    final currentUser = authProvider.user;
    if (currentUser == null) return;

    if (_rating == 0) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('يرجى اختيار عدد النجوم ⭐')),
      );
      return;
    }

    FocusScope.of(context).unfocus();
    setState(() => _isSubmitting = true);

    try {
      final newReview = Review(
        id: '', // Will be generated by Firestore
        targetId: widget.itemId,
        targetType: widget.itemType,
        userId: currentUser.id,
        userName: currentUser.name,
        userImage: currentUser.profileImageUrl ?? '',
        rating: _rating.toInt(), // Convert double to int
        comment: _reviewController.text,
        images: _selectedImages,
        createdAt: DateTime.now(),
        reply: null,
        repliedAt: null,
      );

      await ApiService.addReview(newReview);

      if (!mounted) return;

      setState(() {
        _rating = 0;
        _reviewController.clear();
        _selectedImages.clear();
        _isSubmitting = false;
      });

      // ✅ Fix #94: تحديث قائمة التقييمات وإبلاغ الشاشة الأم بالنجاح
      _refreshReviews();

      final messenger = ScaffoldMessenger.of(context);
      messenger.showSnackBar(
        const SnackBar(
          content: Text('تم إرسال تقييمك بنجاح! شكراً لك.'),
          backgroundColor: Colors.deepPurple,
        ),
      );

    } catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('حدث خطأ، يُرجى المحاولة مرة أخرى'), backgroundColor: Colors.red),
      );
      setState(() => _isSubmitting = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final authProvider = Provider.of<app_auth.AuthProvider>(context);

    if (authProvider.isGuest) {
      return Scaffold(
        appBar: AppBar(title: const Text('إضافة تقييم')),
        body: Center(
          child: Column(
            mainAxisAlignment: MainAxisAlignment.center,
            children: [
              const Icon(Icons.lock_outline, size: 80, color: Colors.grey),
              const SizedBox(height: 16),
              const Text('يجب تسجيل الدخول للتقييم',
                  style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold)),
              const SizedBox(height: 8),
              ElevatedButton(
                onPressed: () => Navigator.pushReplacementNamed(context, '/login'),
                child: const Text('تسجيل الدخول'),
              ),
            ],
          ),
        ),
      );
    }

    return GestureDetector(
      onTap: () => FocusScope.of(context).unfocus(),
      child: Scaffold(
        appBar: AppBar(
          title: Text('تقييم ${widget.itemName}'),
          backgroundColor: Theme.of(context).primaryColor,
          foregroundColor: Colors.white,
          centerTitle: true,
        ),
        body: SingleChildScrollView(
          padding: const EdgeInsets.all(20.0),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              _buildAddReviewSection(context),
              const SizedBox(height: 30),
              const Divider(thickness: 2),
              const SizedBox(height: 10),
              const Text(
                'آراء العملاء',
                style: TextStyle(fontSize: 20, fontWeight: FontWeight.bold),
              ),
              const SizedBox(height: 15),
              _buildReviewsList(),
            ],
          ),
        ),
      ),
    );
  }

  Widget _buildAddReviewSection(BuildContext context) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        Container(
          padding: const EdgeInsets.all(16),
          decoration: BoxDecoration(
            color: Colors.grey[50],
            borderRadius: BorderRadius.circular(12),
            border: Border.all(color: Colors.grey.shade200),
          ),
          child: const Column(
            children: [
              Text('كيف كانت تجربتك؟',
                  style: TextStyle(color: Colors.grey)),
            ],
          ),
        ),
        const SizedBox(height: 20),
        Center(
          child: RatingBar.builder(
            initialRating: _rating,
            minRating: 1,
            direction: Axis.horizontal,
            allowHalfRating: true,
            itemCount: 5,
            itemSize: 45,
            unratedColor: Colors.amber.withValues(alpha: 0.2),
            itemPadding: const EdgeInsets.symmetric(horizontal: 4.0),
            itemBuilder: (context, _) =>
                const Icon(Icons.star, color: Colors.amber),
            onRatingUpdate: (rating) => setState(() => _rating = rating),
          ),
        ),
        const SizedBox(height: 10),
        Center(
          child: Text(
            _rating > 0 ? '$_rating من 5' : 'اضغط للتقييم',
            style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 16),
          ),
        ),
        const SizedBox(height: 20),
        TextField(
          controller: _reviewController,
          maxLines: 3,
          decoration: const InputDecoration(
            hintText: 'اكتب رأيك هنا (اختياري)...',
            border: OutlineInputBorder(),
            alignLabelWithHint: true,
            labelText: 'تفاصيل التجربة',
          ),
        ),
        const SizedBox(height: 15),
        _buildImagePickerSection(),
        const SizedBox(height: 20),
        SizedBox(
          height: 50,
          child: ElevatedButton(
            onPressed:
                (_isSubmitting || _isImageUploading) ? null : _submitReview,
            style: ElevatedButton.styleFrom(
              backgroundColor: Colors.deepPurple,
              foregroundColor: Colors.white,
              shape: RoundedRectangleBorder(
                  borderRadius: BorderRadius.circular(10)),
            ),
            child: _isSubmitting
                ? const SizedBox(
                    height: 24,
                    width: 24,
                    child: CircularProgressIndicator(color: Colors.white))
                : const Text('نشر التقييم',
                    style:
                        TextStyle(fontSize: 18, fontWeight: FontWeight.bold)),
          ),
        ),
      ],
    );
  }

  Widget _buildImagePickerSection() {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        const Text('إضافة صور (اختياري)',
            style: TextStyle(fontWeight: FontWeight.bold)),
        const SizedBox(height: 10),
        SizedBox(
          height: 90,
          child: ListView(
            scrollDirection: Axis.horizontal,
            children: [
              if (_selectedImages.length < 5)
                Padding(
                  padding: const EdgeInsetsDirectional.only(end: 10),
                  child: InkWell(
                    onTap: _isImageUploading ? null : _pickImage,
                    borderRadius: BorderRadius.circular(10),
                    child: Container(
                      width: 90,
                      decoration: BoxDecoration(
                        color: Colors.grey[200],
                        borderRadius: BorderRadius.circular(10),
                        border: Border.all(color: Colors.grey.shade400),
                      ),
                      child: _isImageUploading
                          ? const Center(child: CircularProgressIndicator())
                          : const Column(
                              mainAxisAlignment: MainAxisAlignment.center,
                              children: [
                                Icon(Icons.camera_alt, color: Colors.grey),
                                Text('إضافة',
                                    style: TextStyle(
                                        fontSize: 12, color: Colors.grey)),
                              ],
                            ),
                    ),
                  ),
                ),
              ..._selectedImages.map((img) => Stack(
                    children: [
                      Container(
                        width: 90,
                        margin: const EdgeInsetsDirectional.only(end: 10),
                        decoration: BoxDecoration(
                          borderRadius: BorderRadius.circular(10),
                          image: DecorationImage(
                              image: NetworkImage(img), fit: BoxFit.cover),
                          border: Border.all(color: Colors.grey.shade300),
                        ),
                      ),
                      Positioned(
                        top: 2,
                        right: 12,
                        child: InkWell(
                          onTap: () => _removeImage(img),
                          child: const CircleAvatar(
                            radius: 10,
                            backgroundColor: Colors.red,
                            child: Icon(Icons.close,
                                size: 14, color: Colors.white),
                          ),
                        ),
                      ),
                    ],
                  )),
            ],
          ),
        ),
      ],
    );
  }

  Widget _buildReviewsList() {
    return FutureBuilder<List<Review>>(
      future: _reviewsFuture,
      builder: (context, snapshot) {
        if (snapshot.connectionState == ConnectionState.waiting) {
          return const Center(child: CircularProgressIndicator());
        }
        if (snapshot.hasError) {
          return Center(child: Text('حدث خطأ في تحميل التقييمات: ${snapshot.error}'));
        }

        final reviews = snapshot.data;

        if (reviews == null || reviews.isEmpty) {
          return const Center(
            child: Padding(
              padding: EdgeInsets.all(20.0),
              child: Text('لا توجد تقييمات حتى الآن. كن أول من يقيم!',
                  style: TextStyle(color: Colors.grey)),
            ),
          );
        }

        return ListView.builder(
          shrinkWrap: true,
          physics:
              const NeverScrollableScrollPhysics(),
          itemCount: reviews.length,
          itemBuilder: (context, index) {
            return _buildReviewItem(reviews[index]);
          },
        );
      },
    );
  }

  Widget _buildReviewItem(Review review) {
    final userImage = review.userImage;
    final reply = review.reply;
    final repliedAt = review.repliedAt;
    final reviewImages = review.images;

    return Card(
      margin: const EdgeInsets.only(bottom: 16),
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
      elevation: 2,
      child: Padding(
        padding: const EdgeInsets.all(12.0),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                CircleAvatar(
                  backgroundColor: Colors.grey[200],
                  backgroundImage: (userImage != null && userImage.isNotEmpty)
                      ? NetworkImage(userImage)
                      : null,
                  child: (userImage == null || userImage.isEmpty)
                      ? const Icon(Icons.person, color: Colors.grey)
                      : null,
                ),
                const SizedBox(width: 10),
                Expanded(
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Text(review.userName ?? 'مستخدم',
                          style: const TextStyle(fontWeight: FontWeight.bold)),
                      Text(
                        DateFormat('dd/MM/yyyy').format(review.createdAt),
                        style:
                            const TextStyle(fontSize: 10, color: Colors.grey),
                      ),
                    ],
                  ),
                ),
                Container(
                  padding:
                      const EdgeInsets.symmetric(horizontal: 8, vertical: 4),
                  decoration: BoxDecoration(
                    color: Colors.amber.withValues(alpha: 0.2),
                    borderRadius: BorderRadius.circular(8),
                  ),
                  child: Row(
                    children: [
                      const Icon(Icons.star, size: 14, color: Colors.amber),
                      const SizedBox(width: 4),
                      Text('${review.rating}',
                          style: const TextStyle(
                              fontWeight: FontWeight.bold, fontSize: 12)),
                    ],
                  ),
                ),
              ],
            ),

            const SizedBox(height: 10),

            if (review.comment.isNotEmpty)
              Text(review.comment,
                  style: const TextStyle(fontSize: 14, height: 1.4)),

            if (reviewImages != null && reviewImages.isNotEmpty) ...[
              const SizedBox(height: 10),
              SizedBox(
                height: 70,
                child: ListView.builder(
                  scrollDirection: Axis.horizontal,
                  itemCount: reviewImages.length,
                  itemBuilder: (context, imgIndex) {
                    return Padding(
                      padding: const EdgeInsets.only(left: 8.0),
                      child: ClipRRect(
                        borderRadius: BorderRadius.circular(8),
                        child: CachedImage(
                            imageUrl: reviewImages[imgIndex],
                            width: 70,
                            height: 70,
                            fit: BoxFit.cover),
                      ),
                    );
                  },
                ),
              ),
            ],

            if (reply != null && reply.isNotEmpty) ...[
              const SizedBox(height: 12),
              Container(
                width: double.infinity,
                padding: const EdgeInsets.all(12),
                decoration: BoxDecoration(
                  color: Theme.of(context).primaryColor.withValues(alpha: 0.05),
                  borderRadius: BorderRadius.circular(8),
                  border: Border.all(
                      color: Theme.of(context).primaryColor.withValues(alpha: 0.2)),
                ),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Row(
                      children: [
                        Icon(Icons.store,
                            size: 16, color: Theme.of(context).primaryColor),
                        const SizedBox(width: 6),
                        Text('رد البائع',
                            style: TextStyle(
                                fontWeight: FontWeight.bold,
                                fontSize: 12,
                                color: Theme.of(context).primaryColor)),
                        const Spacer(),
                        if (repliedAt != null)
                          Text(
                            DateFormat('dd/MM').format(repliedAt),
                            style: const TextStyle(
                                fontSize: 10, color: Colors.grey),
                          ),
                      ],
                    ),
                    const SizedBox(height: 6),
                    Text(reply,
                        style: const TextStyle(
                            fontSize: 13, color: Colors.black87)),
                  ],
                ),
              ),
            ],
          ],
        ),
      ),
    );
  }
}
